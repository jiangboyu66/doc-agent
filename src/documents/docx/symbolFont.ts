export function symbolChar(font: string | undefined, charHex: string | undefined): string | null {
  if (!charHex) return null;
  const code = parseInt(charHex, 16);
  if (!Number.isFinite(code)) return null;
  const low = code & 0xff;
  if (!font || /symbol/i.test(font)) {
    if (low >= 0x30 && low <= 0x39) return String.fromCharCode(low);
    return TABLE[low] ?? null;
  }
  return null;
}
